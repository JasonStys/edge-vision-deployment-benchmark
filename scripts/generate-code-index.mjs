/** File: Generates exact function, type, and constant line locations across all source runtimes.
 * Functions: walk, declarations, render, and main logic produce docs/CODE_INDEX.md. Variables:
 * sourceRoots, accepted, and patterns define the indexed surface.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { relative, resolve } from "node:path";

const repository = resolve(import.meta.dirname, "..");
const sourceRoots = ["src", "tests", "scripts", "native/cpp", "native/rust/src"];
const outputPath = resolve(repository, "docs/CODE_INDEX.md");
const accepted = /(?:\.py|\.mjs|\.sh|\.cpp|\.hpp|\.rs|CMakeLists\.txt)$/;
const patterns = [
  [/^\s*(?:async\s+)?def\s+([A-Za-z0-9_]+)/, "function"],
  [/^\s*class\s+([A-Za-z0-9_]+)/, "type"],
  [/^\s*(?:pub\s+)?(?:fn|struct|enum|trait)\s+([A-Za-z0-9_]+)/, "rust declaration"],
  [/^\s*(?:pub\s+)?const\s+([A-Z][A-Z0-9_]+)/, "constant"],
  [/^\s*inline constexpr\s+[^=]+\s+(k[A-Za-z0-9_]+)/, "constant"],
  [/^\s*(?:export\s+)?(?:async\s+)?function\s+([A-Za-z0-9_]+)/, "function"],
  [/^\s*(?:void|int|float|std::[A-Za-z0-9_:<>]+|Model)\s+([A-Za-z0-9_:~]+)\s*\(/, "C++ function"],
];

async function walk(directory) {
  const files = [];
  for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory() && !["build", "target", "__pycache__"].includes(entry.name)) files.push(...await walk(path));
    else if (entry.isFile() && accepted.test(entry.name)) files.push(path);
  }
  return files;
}

function declarations(text) {
  const found = [];
  for (const [offset, line] of text.split(/\r?\n/).entries()) {
    for (const [pattern, kind] of patterns) {
      const match = line.match(pattern);
      if (match?.[1]) {
        found.push({ kind, name: match[1], line: offset + 1 });
        break;
      }
    }
  }
  return found;
}

async function render() {
  const files = (await Promise.all(sourceRoots.map((root) => walk(resolve(repository, root))))).flat();
  const sections = [];
  for (const file of files.sort()) {
    const rows = declarations(await readFile(file, "utf8"));
    if (!rows.length) continue;
    const path = relative(repository, file).replaceAll("\\", "/");
    sections.push(`## \`${path}\`\n\n| Kind | Name | Line |\n|---|---|---:|\n${rows.map((row) => `| ${row.kind} | \`${row.name}\` | ${row.line} |`).join("\n")}`);
  }
  return `# Code Index\n\nGenerated by \`npm run code-index\`. Line numbers refer to committed source and are checked in CI. File headers describe local variables and responsibilities.\n\n${sections.join("\n\n")}\n`;
}

const generated = await render();
if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8");
  if (current !== generated) throw new Error("docs/CODE_INDEX.md is stale; run npm run code-index");
} else {
  await writeFile(outputPath, generated, "utf8");
}

